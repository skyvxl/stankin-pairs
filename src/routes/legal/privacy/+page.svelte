  <h1>Политика конфиденциальности</h1>
  <p class="text-zinc-500 dark:text-zinc-400 text-xs">Последнее обновление: апрель 2025</p>

  <h2>Кто мы</h2>
  <p>
    Это неофициальное приложение для просмотра расписания занятий СТАНКИН. Приложение разработано
    независимым разработчиком и никак не связано с ФГБОУ ВО «МГТУ «СТАНКИН» официально.
  </p>

  <h2>Какие данные собираем</h2>
  <p>
    Само приложение <strong>не собирает, не хранит и не передаёт никаких персональных данных</strong>.
    Выбранная группа и настройки сохраняются исключительно в памяти вашего браузера (localStorage)
    и никуда не отправляются.
  </p>

  <h2>Третьи стороны</h2>
  <p>При использовании приложения данные могут обрабатываться следующими сервисами:</p>
  <ul>
    <li>
      <strong>GitHub (github.com)</strong> — данные расписания хранятся и раздаются через GitHub Raw.
      GitHub может собирать технические данные запросов (IP, User-Agent) в соответствии со своей
      <a href="https://docs.github.com/ru/site-policy/privacy-policies/github-general-privacy-statement" target="_blank" rel="noopener">политикой конфиденциальности</a>.
    </li>
    <li>
      <strong>Vercel (vercel.com)</strong> — приложение развёрнуто на платформе Vercel, которая
      собирает стандартные данные веб-сервера (IP, дата/время запроса, тип браузера) согласно
      своей <a href="https://vercel.com/legal/privacy-policy" target="_blank" rel="noopener">политике конфиденциальности</a>.
    </li>
  </ul>

  <h2>Расписание</h2>
  <p>
    Данные расписания получены разработчиком из внутренних систем СТАНКИН и хранятся в
    репозитории на GitHub. Мы не гарантируем актуальность данных — всегда проверяйте
    официальное расписание на сайте университета.
  </p>

